#!/bin/bash

BIN_PATH="./build_raft/raft_node"

if [ ! -f "$BIN_PATH" ]; then
    echo "❌ 错误：未找到编译产物 $BIN_PATH，请先执行 cmake 编译大盘！"
    exit 1
fi

echo "========================================================================="
echo "🌊 纯自研 3 节点 Raft 分布式集群准备物理点火..."
echo "========================================================================="

# 启动各节点后台运行
$BIN_PATH 1 8881 8882 8883 2>&1 | sed "s/^/[Node-1] /" &
$BIN_PATH 2 8882 8881 8883 2>&1 | sed "s/^/[Node-2] /" &
$BIN_PATH 3 8883 8881 8882 2>&1 | sed "s/^/[Node-3] /" &

echo "🚀 全线节点已在后台完成 EINPROGRESS 注入！"
echo "💡 提示：按下 Ctrl + C 将触发四阶段优雅停机..."

# 捕获 Ctrl+C，等待后台所有节点平稳完成四阶段落盘后再退出
trap 'echo -e "\n🏳️ 收到熔断信号，等待各节点完成四阶段落盘与优雅退出..."; wait; echo "✅ 所有节点已安全退出。"; exit 0' INT

wait