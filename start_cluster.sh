#!/bin/bash

# 刚性编译产物路径定义
BIN_PATH="./build_raft/raft_node"

if [ ! -f "$BIN_PATH" ]; then
    echo "❌ 错误：未找到编译产物 $BIN_PATH，请先执行 cmake 编译大盘！"
    exit 1
fi

echo "========================================================================="
echo "🌊 纯自研 3 节点 Raft 分布式集群准备物理点火..."
echo "========================================================================="

# 1. 启动节点 1 (监听 8881，去连 8882 8883)
$BIN_PATH 1 8881 8882 8883 2>&1 | sed "s/^/[Node-1] /" &
PID_1=$!

# 2. 启动节点 2 (监听 8882，去连 8881 8883)
$BIN_PATH 2 8882 8881 8883 2>&1 | sed "s/^/[Node-2] /" &
PID_2=$!

# 3. 启动节点 3 (监听 8883，去连 8881 8882)
$BIN_PATH 3 8883 8881 8882 2>&1 | sed "s/^/[Node-3] /" &
PID_3=$!

echo "🚀 全线节点已在后台完成 EINPROGRESS 注入！"
echo "💡 提示：按下 Ctrl + C 将自动熔断清理全场存根进程。"

# 刚性拦截 Ctrl+C 信号，防止退出后后台进程沦为僵尸进程孤儿
trap "echo -e '\n🏳️ 收到熔断信号，正在铁腕清场...'; kill $PID_1 $PID_2 $PID_3 2>/dev/null; exit" INT

# 让主线程挂起死守，静等收割后台日志
wait